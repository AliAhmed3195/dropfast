'use client';

import { useState, useEffect } from 'react';
import { useParams } from 'next/navigation';
import { Card } from '@/components/ui/Card';

interface Store {
  id: string;
  name: string;
  slug: string;
  description: string;
  template: string;
  logo?: string;
  address?: string;
  phone?: string;
  email?: string;
  owner: {
    name: string;
  };
}

